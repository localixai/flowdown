/**
 * Writes the two tables of named character references (`&copy;`) the engine decodes:
 *
 *   src/engine/entity-core.ts   the 253 names of HTML 4 (and `&apos;`), in every page
 *   src/engine/entity-table.ts  every HTML5 name, which CommonMark requires, fetched on demand
 *
 * Run it when the `character-entities` packages change: `bun scripts/entities.ts`.
 */
import { characterEntities } from 'character-entities'
import { characterEntitiesHtml4 } from 'character-entities-html4'

const table = (names: string[]) =>
  names.map((name) => `${name}\t${characterEntities[name]}`).join('\n')

const write = async (file: string, constant: string, about: string, names: string[]) => {
  const source = `/**
 * ${about}
 * One \`name<tab>characters\` per line. Generated by scripts/entities.ts; do not edit.
 */
export const ${constant} =
  ${JSON.stringify(table(names))}
`
  await Bun.write(new URL(`../src/engine/${file}`, import.meta.url), source)
  console.log(
    `${file}: ${names.length} names, ${Bun.gzipSync(Buffer.from(source)).length} bytes gzipped`,
  )
}

const core = [...new Set([...Object.keys(characterEntitiesHtml4), 'apos'])].toSorted()
for (const name of core)
  if (!(name in characterEntities)) throw new Error(`not an HTML5 name: ${name}`)

await write(
  'entity-core.ts',
  'ENTITY_CORE',
  'The named character references of HTML 4 and `&apos;`: the ones replies use.',
  core,
)
await write(
  'entity-table.ts',
  'ENTITY_TABLE',
  'Every HTML5 named character reference CommonMark decodes.',
  Object.keys(characterEntities).toSorted(),
)
